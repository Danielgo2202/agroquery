"""Check every gold query: it runs, returns rows, is deterministic and has no
ties at a LIMIT boundary. Also renders benchmark/questions.md for reviewers."""

from __future__ import annotations

import re
import sys

from agroquery.agent.sql_exec import SQLExecutor
from agroquery.config import BENCHMARK_FILE
from agroquery.eval.benchmark import DIFFICULTIES, load_questions
from agroquery.eval.compare import normalize, results_match

LIMIT_RE = re.compile(r"\bLIMIT\s+(\d+)\s*$", re.IGNORECASE)


def tie_at_limit(ex: SQLExecutor, sql: str) -> bool:
    m = LIMIT_RE.search(sql)
    if not m:
        return False
    k = int(m.group(1))
    res = ex.run(sql[: m.start()] + f"LIMIT {k + 1}")
    if not res.ok or len(res.rows) <= k:
        return False
    last, nxt = res.rows[k - 1], res.rows[k]
    nums = [i for i, v in enumerate(last) if isinstance(normalize(v), float)]
    return bool(nums) and all(normalize(last[i]) == normalize(nxt[i]) for i in nums)


def fmt(v) -> str:
    v = normalize(v)
    return f"{v:,.2f}" if isinstance(v, float) else str(v)


def render_markdown(questions, results) -> str:
    lines = [
        "# AgroQuery benchmark",
        "",
        "Generated by `agroquery validate` from `questions.jsonl`. "
        "Each question has a gold SQL query; a model answer is correct when its result set "
        "matches the gold result (execution accuracy).",
        "",
        "| Difficulty | Questions |",
        "|---|---|",
    ]
    for d in DIFFICULTIES:
        lines.append(f"| {d} | {sum(q.difficulty == d for q in questions)} |")
    for q in questions:
        res = results[q.id]
        lines += [
            "",
            f"## {q.id} ({q.difficulty})",
            "",
            q.question,
            "",
            "```sql",
            q.gold_sql,
            "```",
            "",
            f"Result: {len(res.rows)} row(s), {res.elapsed_s * 1000:.0f} ms"
            + (" — order matters" if q.order_matters else ""),
            "",
            "| " + " | ".join(res.columns) + " |",
            "|" + "---|" * len(res.columns),
        ]
        for row in res.rows[:5]:
            lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
        if len(res.rows) > 5:
            lines.append("| " + " | ".join("…" for _ in res.columns) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    questions = load_questions()
    ex = SQLExecutor()
    results, problems = {}, []
    for q in questions:
        first = ex.run(q.gold_sql)
        results[q.id] = first
        if not first.ok:
            problems.append(f"{q.id}: error {first.error}")
            continue
        if first.empty:
            problems.append(f"{q.id}: empty result")
        second = ex.run(q.gold_sql)
        if not results_match(first.rows, second.rows, q.order_matters):
            problems.append(f"{q.id}: non-deterministic result")
        if tie_at_limit(ex, q.gold_sql):
            problems.append(f"{q.id}: tie at LIMIT boundary")
        print(f"{q.id:4s} {q.difficulty:6s} rows={len(first.rows):<5d} "
              f"{first.elapsed_s * 1000:7.0f} ms")
    ex.close()
    (BENCHMARK_FILE.parent / "questions.md").write_text(
        render_markdown(questions, results), encoding="utf-8")
    if problems:
        print("\nPROBLEMS:\n  " + "\n  ".join(problems))
        return 1
    print(f"\nAll {len(questions)} gold queries OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
